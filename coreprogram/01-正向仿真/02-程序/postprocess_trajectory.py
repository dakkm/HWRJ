#!/usr/bin/env python3
"""Post-process trajectory_history.csv from the 01 forward simulation module.

Outputs:
  trajectory_metrics.csv   per-object motion summary (released phase by default)
  trajectory_3d.png        3-D trajectories (if matplotlib is available)
  trajectory_range.png     detector range vs. time (if matplotlib is available)

The script uses the formal per-object trajectory interface generated by the
modified Fortran solver.  It does not reconstruct motion from input parameters.
"""
from __future__ import annotations

import argparse
import csv
import math
import sys
from collections import defaultdict
from pathlib import Path

REQUIRED = {
    "case_id", "frame_id", "time_s", "object_id", "active_flag",
    "released_flag", "motion_stage", "release_time_s",
    "x_m", "y_m", "z_m", "vx_m_s", "vy_m_s", "vz_m_s",
    "speed_m_s", "range_to_detector_m",
}

NUMERIC_FLOAT = {
    "time_s", "release_time_s", "x_m", "y_m", "z_m",
    "vx_m_s", "vy_m_s", "vz_m_s", "speed_m_s", "range_to_detector_m",
}
NUMERIC_INT = {"frame_id", "object_id", "active_flag", "released_flag", "motion_stage"}


def read_rows(path: Path):
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        if not reader.fieldnames:
            raise ValueError("trajectory file has no header")
        missing = REQUIRED.difference(reader.fieldnames)
        if missing:
            raise ValueError("missing required columns: " + ", ".join(sorted(missing)))
        rows = []
        for lineno, row in enumerate(reader, start=2):
            try:
                for k in NUMERIC_FLOAT:
                    row[k] = float(row[k])
                for k in NUMERIC_INT:
                    row[k] = int(row[k])
            except (TypeError, ValueError) as exc:
                raise ValueError(f"invalid numeric value at line {lineno}: {exc}") from exc
            vals = [row[k] for k in NUMERIC_FLOAT]
            if not all(math.isfinite(v) for v in vals):
                raise ValueError(f"non-finite numeric value at line {lineno}")
            rows.append(row)
    if not rows:
        raise ValueError("trajectory file contains no data rows")
    return rows


def select_rows(rows, include_prerelease: bool):
    selected = []
    for r in rows:
        if r["active_flag"] != 1:
            continue
        if not include_prerelease and r["released_flag"] != 1:
            continue
        selected.append(r)
    return selected


def distance(a, b):
    return math.sqrt((a["x_m"] - b["x_m"])**2 +
                     (a["y_m"] - b["y_m"])**2 +
                     (a["z_m"] - b["z_m"])**2)


def build_metrics(rows):
    by_obj = defaultdict(list)
    for r in rows:
        by_obj[r["object_id"]].append(r)

    metrics = []
    for object_id in sorted(by_obj):
        pts = sorted(by_obj[object_id], key=lambda r: (r["time_s"], r["frame_id"]))
        if not pts:
            continue
        path_length = sum(distance(a, b) for a, b in zip(pts[:-1], pts[1:]))
        displacement = distance(pts[0], pts[-1]) if len(pts) > 1 else 0.0
        duration = max(0.0, pts[-1]["time_s"] - pts[0]["time_s"])
        avg_path_speed = path_length / duration if duration > 0.0 else pts[0]["speed_m_s"]
        speeds = [r["speed_m_s"] for r in pts]
        ranges = [r["range_to_detector_m"] for r in pts]
        metrics.append({
            "case_id": pts[0]["case_id"],
            "object_id": object_id,
            "sample_count": len(pts),
            "release_time_s": pts[0]["release_time_s"],
            "trajectory_start_time_s": pts[0]["time_s"],
            "trajectory_end_time_s": pts[-1]["time_s"],
            "trajectory_duration_s": duration,
            "path_length_m": path_length,
            "net_displacement_m": displacement,
            "average_path_speed_m_s": avg_path_speed,
            "min_speed_m_s": min(speeds),
            "max_speed_m_s": max(speeds),
            "min_range_to_detector_m": min(ranges),
            "max_range_to_detector_m": max(ranges),
            "start_x_m": pts[0]["x_m"],
            "start_y_m": pts[0]["y_m"],
            "start_z_m": pts[0]["z_m"],
            "end_x_m": pts[-1]["x_m"],
            "end_y_m": pts[-1]["y_m"],
            "end_z_m": pts[-1]["z_m"],
        })
    return metrics, by_obj


def write_metrics(path: Path, metrics):
    if not metrics:
        raise ValueError("no active trajectory samples remain after filtering")
    fields = list(metrics[0].keys())
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(metrics)


def make_plots(by_obj, outdir: Path):
    try:
        import matplotlib.pyplot as plt
    except Exception as exc:
        print(f"[WARN] matplotlib unavailable; CSV metrics were generated, plots skipped: {exc}", file=sys.stderr)
        return

    # 3-D trajectory
    fig = plt.figure(figsize=(9, 7))
    ax = fig.add_subplot(111, projection="3d")
    for object_id in sorted(by_obj):
        pts = sorted(by_obj[object_id], key=lambda r: (r["time_s"], r["frame_id"]))
        if not pts:
            continue
        ax.plot([p["x_m"] for p in pts], [p["y_m"] for p in pts], [p["z_m"] for p in pts],
                label=f"Object {object_id}")
    ax.set_xlabel("X (m)")
    ax.set_ylabel("Y (m)")
    ax.set_zlabel("Z (m)")
    ax.set_title("Target/Decoy Trajectories")
    if len(by_obj) <= 20:
        ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(outdir / "trajectory_3d.png", dpi=200)
    plt.close(fig)

    # Detector range history
    fig, ax = plt.subplots(figsize=(9, 5.5))
    for object_id in sorted(by_obj):
        pts = sorted(by_obj[object_id], key=lambda r: (r["time_s"], r["frame_id"]))
        if not pts:
            continue
        ax.plot([p["time_s"] for p in pts], [p["range_to_detector_m"] for p in pts],
                label=f"Object {object_id}")
    ax.set_xlabel("Time (s)")
    ax.set_ylabel("Range to detector (m)")
    ax.set_title("Object-Detector Range History")
    ax.grid(True, alpha=0.25)
    if len(by_obj) <= 20:
        ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(outdir / "trajectory_range.png", dpi=200)
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description="Post-process 01 module trajectory_history.csv")
    parser.add_argument("--input", default="trajectory_history.csv", help="trajectory_history.csv path")
    parser.add_argument("--outdir", default="trajectory_postprocess", help="output directory")
    parser.add_argument("--include-prerelease", action="store_true",
                        help="include carrier-attached pre-release samples; default uses released phase only")
    parser.add_argument("--no-plot", action="store_true", help="generate metrics CSV only")
    args = parser.parse_args()

    input_path = Path(args.input).resolve()
    outdir = Path(args.outdir).resolve()
    outdir.mkdir(parents=True, exist_ok=True)

    rows = read_rows(input_path)
    selected = select_rows(rows, args.include_prerelease)
    metrics, by_obj = build_metrics(selected)
    metrics_path = outdir / "trajectory_metrics.csv"
    write_metrics(metrics_path, metrics)

    if not args.no_plot:
        make_plots(by_obj, outdir)

    print(f"trajectory input : {input_path}")
    print(f"rows read        : {len(rows)}")
    print(f"rows processed   : {len(selected)}")
    print(f"objects          : {len(metrics)}")
    print(f"metrics output   : {metrics_path}")


if __name__ == "__main__":
    main()
